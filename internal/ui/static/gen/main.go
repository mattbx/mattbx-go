//go:build ignore

// Command gen writes internal/ui/static/chroma.css.
//
// Rendered post HTML carries only Chroma's class names (never inline styles),
// so one document can be themed twice.
//
// Both themes are wrapped in a media query, and that matters: Chroma emits a
// rule only for the tokens a style explicitly defines. If the light rules were
// left unscoped, any token that github-dark leaves at its default would keep
// the light theme's near-black foreground and become unreadable on the dark
// background. Scoping both means exactly one complete theme applies at a time.
//
// "prefers-color-scheme: light" also matches users who have expressed no
// preference, so the light theme remains the effective default.
//
// Run with: go generate ./internal/ui/...
package main

import (
	"bytes"
	"fmt"
	"log"
	"os"
	"strings"

	chromahtml "github.com/alecthomas/chroma/v2/formatters/html"
	"github.com/alecthomas/chroma/v2/styles"
)

const (
	lightStyle = "github"
	darkStyle  = "github-dark"
	outPath    = "internal/ui/static/chroma.css"
)

func main() {
	var out bytes.Buffer
	out.WriteString("/* Generated by internal/ui/static/gen/main.go — do not edit.\n")
	fmt.Fprintf(&out, "   Syntax highlighting: %s (light) / %s (dark).\n", lightStyle, darkStyle)
	out.WriteString("   Both themes are scoped so neither leaks tokens into the other. */\n")

	for _, theme := range []struct{ query, style string }{
		{"light", lightStyle},
		{"dark", darkStyle},
	} {
		block, err := css(theme.style)
		if err != nil {
			log.Fatal(err)
		}
		fmt.Fprintf(&out, "\n@media (prefers-color-scheme: %s) {\n", theme.query)
		out.WriteString(indent(block))
		out.WriteString("}\n")
	}

	if err := os.WriteFile(outPath, out.Bytes(), 0o644); err != nil {
		log.Fatal(err)
	}
	fmt.Printf("wrote %s (%d bytes)\n", outPath, out.Len())
}

func css(name string) (string, error) {
	style := styles.Get(name)
	if style == nil {
		return "", fmt.Errorf("unknown chroma style %q", name)
	}
	// styles.Get falls back to a default rather than returning nil for an
	// unknown name, so confirm we got the style we actually asked for.
	if style.Name != name {
		return "", fmt.Errorf("chroma style %q is not registered (got %q)", name, style.Name)
	}
	var buf bytes.Buffer
	if err := chromahtml.New(chromahtml.WithClasses(true)).WriteCSS(&buf, style); err != nil {
		return "", err
	}
	return buf.String(), nil
}

func indent(block string) string {
	var b strings.Builder
	for line := range strings.SplitSeq(strings.TrimRight(block, "\n"), "\n") {
		if strings.TrimSpace(line) == "" {
			b.WriteString("\n")
			continue
		}
		b.WriteString("  " + line + "\n")
	}
	return b.String()
}
